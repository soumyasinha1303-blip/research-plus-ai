import React, { useState } from "react";
import { Download, Copy, Check, X, FileText, Code } from "lucide-react";
import { SynthesisReport } from "../types/index.ts";

interface ExportModalProps {
  report: SynthesisReport;
  onClose: () => void;
}

export const ExportModal: React.FC<ExportModalProps> = ({ report, onClose }) => {
  const [format, setFormat] = useState<"markdown" | "json" | "bibtex">("markdown");
  const [copied, setCopied] = useState(false);

  const content = report.content_json;

  const generateMarkdown = () => {
    let md = `# ${content.title}\n\n`;
    md += `*Generated by OmniResearch AI on ${new Date(report.created_at).toLocaleDateString()}*\n\n`;
    md += `## Executive Summary\n${content.executiveSummary}\n\n`;
    md += `## Comparative Analysis Matrix\n`;

    content.comparativeAnalysis.forEach((comp, idx) => {
      md += `\n### ${idx + 1}. ${comp.theme}\n`;
      md += `**Consensus:** ${comp.consensus}\n\n`;
      md += `**Contradictions & Tension:** ${comp.contradictions}\n\n`;
      md += `**Supporting Documents:** ${comp.supportingDocIds.join(", ")}\n`;
    });

    if (content.researchGaps?.length) {
      md += `\n## Identified Research Gaps\n`;
      content.researchGaps.forEach((gap) => {
        md += `- ${gap}\n`;
      });
    }

    if (content.futureDirections?.length) {
      md += `\n## Recommended Future Directions\n`;
      content.futureDirections.forEach((dir) => {
        md += `- ${dir}\n`;
      });
    }

    return md;
  };

  const generateBibtex = () => {
    const titles = content.metadata?.documentTitles || [];
    if (titles.length === 0) {
      return `@article{omniresearch_${report.id.slice(0, 8)},\n  title = {${content.title}},\n  year = {2025},\n  note = {OmniResearch AI Synthesis Engine}\n}`;
    }

    return titles
      .map((d, idx) => {
        const key = `doc_ref_${idx + 1}_${report.id.slice(0, 4)}`;
        return `@misc{${key},\n  title = {${d.title}},\n  year = {2025},\n  howpublished = {OmniResearch Academic Knowledge Base}\n}`;
      })
      .join("\n\n");
  };

  const exportText =
    format === "markdown"
      ? generateMarkdown()
      : format === "json"
      ? JSON.stringify(content, null, 2)
      : generateBibtex();

  const handleCopy = () => {
    navigator.clipboard.writeText(exportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const ext = format === "markdown" ? "md" : format === "json" ? "json" : "bib";
    const mime = format === "json" ? "application/json" : "text/plain";
    const blob = new Blob([exportText], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `synthesis_report_${report.id.slice(0, 8)}.${ext}`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/75 p-4 backdrop-blur-sm animate-in fade-in">
      <div className="w-full max-w-2xl rounded-2xl border border-slate-800 bg-slate-900 shadow-2xl">
        <div className="flex items-center justify-between border-b border-slate-800 px-6 py-4">
          <div className="flex items-center gap-2">
            <Download className="h-4 w-4 text-indigo-400" />
            <h3 className="text-base font-bold text-white">Export Research Synthesis</h3>
          </div>
          <button onClick={onClose} className="rounded-lg p-1 text-slate-400 hover:bg-slate-800 hover:text-white">
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Format Selector */}
        <div className="flex border-b border-slate-800 px-6">
          {(["markdown", "json", "bibtex"] as const).map((fmt) => (
            <button
              key={fmt}
              onClick={() => setFormat(fmt)}
              className={`py-3 text-xs font-semibold uppercase tracking-wider transition mr-6 border-b-2 ${
                format === fmt
                  ? "border-indigo-500 text-indigo-400"
                  : "border-transparent text-slate-400 hover:text-slate-200"
              }`}
            >
              {fmt}
            </button>
          ))}
        </div>

        {/* Preview Content */}
        <div className="p-6">
          <pre className="h-80 overflow-y-auto rounded-xl border border-slate-800 bg-slate-950 p-4 font-mono text-xs text-slate-300 leading-relaxed">
            {exportText}
          </pre>

          <div className="mt-5 flex items-center justify-between">
            <p className="text-xs text-slate-400">
              Publication-ready structured format for LaTeX, Markdown, or JSON pipelines.
            </p>
            <div className="flex items-center gap-2">
              <button
                onClick={handleCopy}
                className="flex items-center gap-1.5 rounded-lg border border-slate-800 bg-slate-800/80 px-4 py-2 text-xs font-medium text-slate-200 transition hover:bg-slate-700"
              >
                {copied ? <Check className="h-3.5 w-3.5 text-emerald-400" /> : <Copy className="h-3.5 w-3.5" />}
                <span>{copied ? "Copied" : "Copy to Clipboard"}</span>
              </button>
              <button
                onClick={handleDownload}
                className="flex items-center gap-1.5 rounded-lg bg-indigo-600 px-4 py-2 text-xs font-semibold text-white shadow-md shadow-indigo-600/20 transition hover:bg-indigo-500"
              >
                <Download className="h-3.5 w-3.5" />
                <span>Download .{format === "markdown" ? "md" : format === "json" ? "json" : "bib"}</span>
              </button>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
